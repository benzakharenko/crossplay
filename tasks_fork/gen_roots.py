#!/usr/bin/env python3
"""Regenerate src/apps_local/tasks/TasksRoots.h from a system trust store.

api.notion.com is served through Cloudflare, whose certificates come from a
pool of CAs (Let's Encrypt, Google Trust Services, SSL.com, Sectigo) and can
switch between them at any renewal. So the app trusts the pool's roots, not
one pin. A newer bundle can also be dropped on the card at
/.crosspoint/tasks/roots.pem, which wins over this baked copy.

Usage: gen_roots.py [CERT_DIR]   (default /etc/ssl/certs)
"""
import datetime
import os
import sys

ROOTS = [
    "ISRG_Root_X1", "ISRG_Root_X2",
    "GTS_Root_R1", "GTS_Root_R3", "GTS_Root_R4",
    "SSL.com_TLS_RSA_Root_CA_2022", "SSL.com_TLS_ECC_Root_CA_2022",
    "SSL.com_Root_Certification_Authority_RSA", "SSL.com_Root_Certification_Authority_ECC",
    "Certum_Trusted_Network_CA",
    "USERTrust_RSA_Certification_Authority", "USERTrust_ECC_Certification_Authority",
    "Sectigo_Public_Server_Authentication_Root_R46", "Sectigo_Public_Server_Authentication_Root_E46",
]

def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/certs"
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "src/apps_local/tasks/TasksRoots.h")
    lines = [
        "#pragma once",
        "",
        "// CA roots for api.notion.com (Cloudflare's CA pool). Generated by",
        "// tasks_fork/gen_roots.py on %s; do not edit by hand." % datetime.date.today().isoformat(),
        "// wolfSSL's load_verify_buffer accepts concatenated PEM. An SD file at",
        "// /.crosspoint/tasks/roots.pem replaces this bundle.",
        "",
        "namespace tasks {",
        "",
        "inline constexpr char kNotionCaRoots[] =",
    ]
    for name in ROOTS:
        pem = open(os.path.join(d, name + ".pem")).read().strip().splitlines()
        lines.append("    // " + name.replace("_", " "))
        for l in pem:
            lines.append('    "%s\\n"' % l)
    lines[-1] += ";"
    lines += ["", "}  // namespace tasks", ""]
    open(out, "w").write("\n".join(lines))
    print("wrote", out, len(ROOTS), "roots")

main()
